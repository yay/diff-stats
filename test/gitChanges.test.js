const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync, mkdirSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { execFileSync } = require('node:child_process')
const { collectChanges, GitRunner } = require('../out/gitChanges')

function repository(t) {
  const root = mkdtempSync(join(tmpdir(), 'diff-stats-test-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' })
  const write = (name, content) => writeFileSync(join(root, name), content)
  git('init', '-q')
  git('config', 'user.name', 'Extension Test')
  git('config', 'user.email', 'test@example.invalid')
  git('config', 'commit.gpgsign', 'false')
  const runner = new GitRunner('git', root)
  t.after(() => runner.dispose())
  return { root, git, write, count: () => collectChanges(runner, root) }
}

test('clean, modified, staged, partially staged, committed and discarded changes', async t => {
  const { git, write, count } = repository(t)
  write('file', 'one\ntwo\n')
  git('add', '.')
  git('commit', '-qm', 'Initial')
  assert.deepEqual(await count(), { files: 0, insertions: 0, deletions: 0 })
  write('file', 'one\nchanged\nextra\n')
  assert.deepEqual(await count(), { files: 1, insertions: 2, deletions: 1 })
  git('add', '.')
  assert.deepEqual(await count(), { files: 1, insertions: 2, deletions: 1 })
  write('file', 'one\nchanged\nextra\nlast\n')
  assert.deepEqual(await count(), { files: 1, insertions: 3, deletions: 1 })
  write('file', 'one\ntwo\n')
  assert.deepEqual(await count(), { files: 1, insertions: 0, deletions: 0 })
  git('reset', '--hard', '-q', 'HEAD')
  assert.deepEqual(await count(), { files: 0, insertions: 0, deletions: 0 })
  write('file', 'one\nchanged\n')
  git('add', '.')
  git('commit', '-qm', 'Change')
  assert.deepEqual(await count(), { files: 0, insertions: 0, deletions: 0 })
})

test('deleted, renamed and binary files count once with net line totals', async t => {
  const { root, git, write, count } = repository(t)
  write('remove', 'a\nb\n')
  write('rename', 'same\n')
  write('binary', Buffer.from([0, 1, 2]))
  git('add', '.')
  git('commit', '-qm', 'Initial')
  rmSync(join(root, 'remove'))
  git('mv', 'rename', 'renamed\twith\ncharacters')
  write('binary', Buffer.from([0, 3, 4, 5]))
  assert.deepEqual(await count(), { files: 3, insertions: 0, deletions: 2 })
})

test('untracked files, ignored files, nested folders and unusual filenames', async t => {
  const { root, git, write, count } = repository(t)
  write('.gitignore', 'ignored\n')
  git('add', '.')
  git('commit', '-qm', 'Initial')
  write('ignored', 'ignored\n')
  write('-leading space\tand\nnewline', 'a\nb')
  write('empty', '')
  write('binary', Buffer.from([0, 1, 2]))
  mkdirSync(join(root, 'nested'))
  write('nested/file', 'last\n')
  assert.deepEqual(await count(), { files: 4, insertions: 3, deletions: 0 })
})

test('unborn repository combines staged and unstaged contents against the empty tree', async t => {
  const { git, write, count } = repository(t)
  assert.deepEqual(await count(), { files: 0, insertions: 0, deletions: 0 })
  write('staged', 'old\n')
  git('add', '.')
  write('staged', 'new\nextra\n')
  write('untracked', 'another\n')
  assert.deepEqual(await count(), { files: 2, insertions: 3, deletions: 0 })
})

test('repositories stay isolated and failures reject instead of returning zero counts', async t => {
  const first = repository(t)
  const second = repository(t)
  first.write('file', 'one\n')
  second.write('file', 'one\ntwo\n')
  assert.equal((await first.count()).insertions, 1)
  assert.equal((await second.count()).insertions, 2)
  const missing = new GitRunner('nonexistent-diff-stats-git', first.root)
  await assert.rejects(collectChanges(missing, first.root))
  missing.dispose()
  const cancelled = new GitRunner('git', first.root)
  cancelled.dispose()
  await assert.rejects(collectChanges(cancelled, first.root), /cancelled/)
})
